ALL = {**TOPICS, **HELP_TYPES}


def clean(values, allowed) -> list:
    """Оставляет только известные теги, без повторов, сохраняя порядок."""
    out = []
    for v in values or []:
        v = str(v).strip().lower()
        if v in allowed and v not in out:
            out.append(v)
    return out
